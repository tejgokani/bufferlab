"""iperf3 wrapper.

Safety rules: traffic is only generated by an explicit call naming a host and port, the caller must have
confirmed it, no system network settings are touched, and no administrator rights are needed.
Results are *measurements* and are kept apart from simulation results.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import asdict, dataclass
from typing import Any


class MeasureError(RuntimeError):
    pass


def find_iperf3() -> str | None:
    return shutil.which("iperf3")


INSTALL_HINT = (
    "iperf3 was not found on PATH. Install it: macOS `brew install iperf3`; Debian/Ubuntu "
    "`sudo apt install iperf3`; Windows `winget install iperf3` or https://iperf.fr/iperf-download.php"
)


@dataclass(frozen=True)
class IperfResult:
    source: str  # always "measured (iperf3)"
    host: str
    port: int
    protocol: str
    duration_s: float
    reverse: bool
    throughput_mbps: float
    retransmits: int | None = None
    jitter_ms: float | None = None
    lost_percent: float | None = None
    iperf3_version: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def parse_iperf_json(
    data: dict[str, Any], host: str, port: int, protocol: str, reverse: bool
) -> IperfResult:
    if "error" in data:
        raise MeasureError(f"iperf3 reported: {data['error']}")
    end = data.get("end") or {}
    start = data.get("start") or {}
    if protocol == "udp":
        s = end.get("sum") or {}
        bps = s.get("bits_per_second")
    else:
        s = end.get("sum_received") or {}
        bps = s.get("bits_per_second")
    if bps is None:
        raise MeasureError("iperf3 output did not contain a throughput summary")
    sent = end.get("sum_sent") or {}
    return IperfResult(
        source="measured (iperf3)",
        host=host,
        port=port,
        protocol=protocol,
        duration_s=float(s.get("seconds", 0.0)),
        reverse=reverse,
        throughput_mbps=bps / 1e6,
        retransmits=sent.get("retransmits") if protocol == "tcp" else None,
        jitter_ms=s.get("jitter_ms") if protocol == "udp" else None,
        lost_percent=s.get("lost_percent") if protocol == "udp" else None,
        iperf3_version=(start.get("version") or None),
    )


def run_client(
    host: str,
    port: int = 5201,
    duration_s: int = 10,
    protocol: str = "tcp",
    reverse: bool = False,
    udp_rate_mbps: float | None = None,
    parallel: int = 1,
    *,
    confirmed: bool = False,
    exe: str | None = None,
) -> IperfResult:
    if not confirmed:
        raise MeasureError("refusing to send traffic without explicit confirmation")
    if not host or host.startswith("-"):
        raise MeasureError(f"invalid host {host!r}")
    if protocol not in ("tcp", "udp"):
        raise MeasureError("protocol must be tcp or udp")
    if not 1 <= duration_s <= 600 or not 1 <= parallel <= 16 or not 1 <= port <= 65535:
        raise MeasureError("duration (1-600 s), parallel streams (1-16) or port out of range")
    exe = exe or find_iperf3()
    if not exe:
        raise MeasureError(INSTALL_HINT)
    cmd = [exe, "-c", host, "-p", str(port), "-t", str(duration_s), "-P", str(parallel), "-J"]
    if protocol == "udp":
        cmd += ["-u"]
        if udp_rate_mbps:
            cmd += ["-b", f"{udp_rate_mbps}M"]
    if reverse:
        cmd += ["-R"]
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=duration_s + 30, check=False
        )
    except subprocess.TimeoutExpired:
        raise MeasureError("iperf3 timed out") from None
    except OSError as exc:
        raise MeasureError(f"could not execute iperf3: {exc}") from None
    try:
        data = json.loads(proc.stdout)
    except ValueError:
        raise MeasureError(
            f"iperf3 failed (exit {proc.returncode}): {proc.stderr.strip() or proc.stdout.strip()}"
        ) from None
    return parse_iperf_json(data, host, port, protocol, reverse)
